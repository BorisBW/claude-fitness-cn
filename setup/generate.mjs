// Turns the setup-form answers into the three memory files Coach Paddy reads.
// Pure functions, no I/O — server.mjs decides where (and whether) to write them.

const DAYS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
const DAYS_ZH = { Mon: '周一', Tue: '周二', Wed: '周三', Thu: '周四', Fri: '周五', Sat: '周六', Sun: '周日' };

const SPORT_LABEL = {
  running: ['Road running', '路跑'],
  trail: ['Trail running', '越野跑'],
  hyrox: ['Hyrox / functional fitness', 'Hyrox / 功能性体能'],
  cycling: ['Cycling', '骑行'],
  triathlon: ['Triathlon', '铁人三项'],
  strength: ['Strength training', '力量训练'],
  general: ['General fitness', '综合健身'],
};

const WEARABLE_LABEL = {
  garmin: 'Garmin', coros: 'Coros', whoop: 'WHOOP', apple: 'Apple Watch', none: '—',
};

function n(v, d = 0) { const x = Number(v); return Number.isFinite(x) ? x : d; }
function today() { return new Date().toISOString().slice(0, 10); }

// Spread N run days and M strength days over a week. Long run lands on Saturday,
// strength never lands on the day before the long run, doubles up only when it must.
export function weekSkeleton(runDays, strengthDays) {
  const week = Object.fromEntries(DAYS.map((d) => [d, []]));
  const runOrder = ['Sat', 'Tue', 'Thu', 'Sun', 'Wed', 'Mon', 'Fri'];
  const strOrder = ['Mon', 'Thu', 'Wed', 'Sun', 'Tue', 'Sat', 'Fri'];
  const runs = runOrder.slice(0, Math.min(7, runDays));
  runs.forEach((d, i) => week[d].push(i === 0 && runDays > 0 ? 'long' : i === 1 && runDays >= 3 ? 'quality' : 'easy'));
  let placed = 0;
  const place = (ok) => {
    for (const d of strOrder) {
      if (placed >= strengthDays) return;
      if (!week[d].includes('strength') && ok(d)) { week[d].push('strength'); placed++; }
    }
  };
  place((d) => week[d].length === 0 && !(d === 'Fri' && runs.includes('Sat'))); // empty days, legs fresh before the long run
  place((d) => week[d].length === 0);                                             // any empty day beats doubling up
  place((d) => !week[d].includes('long'));                                        // double up, never on long-run day
  return week;
}

function sessionText(kind, zh) {
  return {
    long: zh ? '长距离 Easy' : 'Long run (easy)',
    quality: zh ? '质量课（节奏 / 间歇，由教练定）' : 'Quality session (tempo / intervals, coach decides)',
    easy: zh ? 'Easy 跑' : 'Easy run',
    strength: zh ? '力量课' : 'Strength',
  }[kind];
}

// ---------- Coach Memory ----------

export function coachMemory(a) {
  const zh = a.language === 'zh';
  const sport = (SPORT_LABEL[a.sport] || SPORT_LABEL.general)[zh ? 1 : 0];
  const race = a.raceName ? `${a.raceName}${a.raceDate ? ` (${a.raceDate})` : ''}${a.raceTarget ? ` → ${a.raceTarget}` : ''}` : (zh ? '暂无目标赛事' : 'No target race yet');
  const injuries = (a.injuries || '').trim();
  const tone = ({
    direct: ['Direct: blunt, opinionated, swears when earned', '直接：有话直说，有立场，该骂就骂'],
    gentle: ['Gentle: honest, no swearing, no roasting', '温和：照样诚实，不骂人不用脏话'],
    analyst: ['Analyst: numbers first, one-line verdict, no banter', '分析师：数据优先，结论一句话，不闲聊'],
    drill: ['Drill sergeant: short orders, zero excuses', '魔鬼教练：短句命令，不接受借口'],
    buddy: ['Training buddy: warm, encouraging, celebrates small wins', '陪练搭子：温暖鼓励，小进步也庆祝'],
  }[a.tone] || ['Direct', '直接'])[zh ? 1 : 0];

  if (zh) return `# Coach Memory

> Coach Paddy 的长期记忆。每次对话开始先读这个文件。由 \`npm run setup\` 于 ${today()} 生成，之后由教练维护。

## 运动员档案
- **姓名**: ${a.name || '（未填）'}
- **年龄**: ${a.age || '（未填）'}
- **性别**: ${a.gender || '（未填）'}
- **主项**: ${sport}
- **目标**: ${a.goal || '（未填）'}
- **目标赛事**: ${race}
- **每周训练**: 跑/有氧 ${n(a.runDays)} 天 · 力量 ${n(a.strengthDays)} 天
- **设备**: ${WEARABLE_LABEL[a.wearable]}${a.region === 'cn' && (a.wearable === 'garmin' || a.wearable === 'coros') ? '（中国区账号）' : ''}
- **力量记录**: ${a.xunjiToken ? '训记（Xunji）' : '无，晚上口头报。以后随时可以把训记 token 发给教练接上'}
- **教练风格**: ${tone}

## 伤病 / 需要盯的部位
${injuries ? injuries.split('\n').map((l) => `- ${l.trim()}`).filter((l) => l !== '- ').join('\n') : '- 无（运动员填表时未报伤病）'}

> 规则：这里列的每个部位，morning report 的 Readiness 伤病项都要看昨天日志有没有新信号；evening recap 必问。

## 基线（前 28 天自动建立）
- 第 1 天: ${today()}
- HRV / RHR / 睡眠的正常带由 Athlete Bio Data 每日表的前 28 行算出。**不满 14 天前，报告里要写明「基线建立中 第 X/28 天」**，HRV 用设备标签法，不用 SWC。

## 教练笔记
- ${today()}: 完成 setup，首次对话。先用 \`/fitness-coach check\` 验证数据连通，再 \`/fitness-coach plan\` 把训练计划细化。
`;

  return `# Coach Memory

> Coach Paddy's long-term memory. Read this file at the start of every conversation. Generated by \`npm run setup\` on ${today()}; maintained by the coach from here on.

## Athlete Profile
- **Name**: ${a.name || '(not given)'}
- **Age**: ${a.age || '(not given)'}
- **Gender**: ${a.gender || '(not given)'}
- **Main sport**: ${sport}
- **Goal**: ${a.goal || '(not given)'}
- **Target race**: ${race}
- **Weekly schedule**: ${n(a.runDays)} run/cardio days · ${n(a.strengthDays)} strength days
- **Wearable**: ${WEARABLE_LABEL[a.wearable]}${a.region === 'cn' && (a.wearable === 'garmin' || a.wearable === 'coros') ? ' (China-region account)' : ''}
- **Strength log**: ${a.xunjiToken ? 'Xunji (训记)' : 'none — athlete reports verbally in the evening. A Xunji token can be handed to the coach in chat any time'}
- **Coaching tone**: ${tone}

## Injuries / things to watch
${injuries ? injuries.split('\n').map((l) => `- ${l.trim()}`).filter((l) => l !== '- ').join('\n') : '- None reported at setup'}

> Rule: for every item listed here, the morning Readiness injury term checks yesterday's log for new signals, and the evening recap always asks.

## Baselines (built automatically over the first 28 days)
- Day 1: ${today()}
- Normal bands for HRV / RHR / sleep come from the first 28 rows of the Athlete Bio Data daily table. **Until day 14, every report must say "baseline building: day X/28"** and HRV is scored with the device's own label, not SWC.

## Coach Notes
- ${today()}: Setup completed, first conversation. Run \`/fitness-coach check\` to verify data access, then \`/fitness-coach plan\` to refine the training plan.
`;
}

// ---------- Training Plan ----------

export function trainingPlan(a) {
  const zh = a.language === 'zh';
  const week = weekSkeleton(n(a.runDays), n(a.strengthDays));
  const rows = DAYS.map((d) => {
    const s = week[d].map((k) => sessionText(k, zh)).join(' → ') || (zh ? '休息' : 'Rest');
    return `| ${zh ? DAYS_ZH[d] : d} | ${s} | |`;
  }).join('\n');

  if (zh) return `# Training Plan

> 当前训练计划。Coach Paddy 读取并更新这个文件。由 setup 于 ${today()} 生成的**骨架**，细节（配速、重量、动作）请用 \`/fitness-coach plan\` 和教练一起填。

## 当前阶段
- **阶段**: 起步 / 基础期
- **目标**: ${a.goal || '（待定）'}
- **目标赛事**: ${a.raceName || '（暂无）'} ${a.raceDate || ''}

## 周结构（骨架）

| 天 | 训练 | 要点 |
|---|---|---|
${rows}

- 每周 ${n(a.runDays)} 次跑/有氧 + ${n(a.strengthDays)} 次力量
- 长距离排周六，力量不排在长距离前一天
- Easy 跑看配速 + 能说完整句子，不设心率上限

## 力量课（待填）

| 动作 | 组 × 次 | 备注 |
|---|---|---|
| | | |

## 每日恢复（10 分钟）
- [ ] 拉伸
- [ ] 泡沫轴

## 跑前激活（5 分钟）
- [ ] 臀桥 × 10
- [ ] A-Skip × 20m
- [ ] 后踢腿 × 20m

---

*最后更新: ${today()}（setup 生成）*
`;

  return `# Training Plan

> Your current training plan. Coach Paddy reads and updates this file. This is a **skeleton** generated by setup on ${today()} — fill in paces, weights and exercises together with the coach via \`/fitness-coach plan\`.

## Current Block
- **Phase**: Getting started / base
- **Goal**: ${a.goal || '(to be set)'}
- **Target race**: ${a.raceName || '(none yet)'} ${a.raceDate || ''}

## Weekly Structure (skeleton)

| Day | Session | Notes |
|---|---|---|
${rows}

- ${n(a.runDays)} run/cardio + ${n(a.strengthDays)} strength sessions per week
- Long run on Saturday; no strength the day before it
- Easy runs are paced by feel and the talk test, no HR cap

## Strength (to fill in)

| Exercise | Sets × Reps | Notes |
|---|---|---|
| | | |

## Daily Recovery (10 min)
- [ ] Stretching
- [ ] Foam roll

## Pre-Run Warm-Up (5 min)
- [ ] Glute Bridge × 10
- [ ] A-Skip × 20m
- [ ] Butt Kicks × 20m

---

*Last updated: ${today()} (generated by setup)*
`;
}

// ---------- Athlete Bio Data ----------

export function bioData(a) {
  const zh = a.language === 'zh';
  const energyCol = a.wearable === 'garmin' ? 'Body Battery' : a.wearable === 'whoop' ? 'Recovery %' : (zh ? '能量(主观1-5)' : 'Energy (1-5)');
  if (zh) return `# Athlete Bio Data

> 每日恢复数据。Coach Paddy 在 morning report 时写入当天一行。**前 28 行是基线建立期**。

## 每日更新

| 日期 | 睡眠评分 | RHR | HRV (ms) | HRV 状态 | ${energyCol} | 备注 |
|---|---|---|---|---|---|---|

## 体成分（每周日空腹）

| 日期 | 体重 kg | 体脂 % | 备注 |
|---|---|---|---|

## 身体维度（每月第一个周日）

| 日期 | 腰 | 臀 | 胸 | 大腿 | 小腿 | 备注 |
|---|---|---|---|---|---|---|
`;
  return `# Athlete Bio Data

> Daily recovery tracking. Coach Paddy adds today's row during the morning report. **The first 28 rows are the baseline-building period.**

## Daily Updates

| Date | Sleep | RHR | HRV (ms) | HRV status | ${energyCol} | Notes |
|---|---|---|---|---|---|---|

## Body Composition (Sunday mornings, fasted)

| Date | Weight kg | Body fat % | Notes |
|---|---|---|---|

## Measurements (first Sunday of the month)

| Date | Waist | Hips | Chest | Thigh | Calf | Notes |
|---|---|---|---|---|---|---|
`;
}

export function generateFiles(a) {
  return [
    { name: 'Coach Memory.md', content: coachMemory(a) },
    { name: 'Training Plan.md', content: trainingPlan(a) },
    { name: 'Athlete Bio Data.md', content: bioData(a) },
  ];
}
